// =====================================================================
// Лабораторна робота 6. lib/uk_stemmer.js
// Простий стемер української мови для повнотекстового пошуку в MongoDB
// Community. Вбудований текстовий індекс не має української мови
// (лише default_language: 'none' без стемінгу), тому слова зводяться
// до основи на рівні застосунку і зберігаються в полі search_terms.
//
// Алгоритм (легкий стемер, light stemming):
//   1) нижній регістр, видалення апострофа (пам'ять -> память), ґ -> г;
//   2) відкидання стоп-слів і слів коротших за 3 символи;
//   3) відкидання найдовшого флективного закінчення (відмінки іменників
//      і прикметників; дієслівні закінчення не відкидаються, бо -ати,
//      -ять, -ла плутаються з іменниками: Карпати, пам'ять, новела), основа >= 3 символів;
//   4) відкидання суфіксів -ськ/-цьк/-зьк (карпатськ -> карпат),
//      кінцевого -ь і заміна -нн на -н (кохання, коханий -> кохан).
// =====================================================================

globalThis.UkStem = (function () {
  const STOP = new Set(('і й та а але в у на з із зі до про по за від для як що це не ні чи або його її їх він вона ' +
    'воно вони ми ви я ти той та те ця цей ці ті при через над під між без так же ж би б вже ще лише тільки ' +
    'усі всі весь свій своя свою свої який яка яке які де коли там тут хто').split(' '));

  // Закінчення від найдовших до найкоротших
  const ENDINGS = [
    'ього', 'ьому',
    'ями', 'ами', 'ові', 'еві', 'єві', 'ого', 'ому', 'ими', 'іми',
    'ою', 'єю', 'ею', 'ям', 'ам', 'ом', 'ем', 'єм', 'ах', 'ях', 'ів', 'їв', 'ей', 'ий', 'ій', 'ої', 'их', 'іх', 'им', 'ім',
    'ія', 'ії', 'ію', 'ья', 'ью',
    'а', 'я', 'о', 'е', 'є', 'и', 'і', 'ї', 'у', 'ю', 'й', 'ь'
  ];
  const DERIV = ['ськ', 'цьк', 'зьк'];

  function normalize(text) {
    return String(text || '').toLowerCase()
      .replace(/['’ʼ`]/g, '')
      .replace(/ґ/g, 'г')
      .replace(/[^a-zа-яіїє0-9]+/g, ' ')
      .trim();
  }

  function stem(word) {
    let w = word;
    if (w.length < 4 || /^[0-9a-z]+$/.test(w)) return w;
    for (const e of ENDINGS) {
      if (w.endsWith(e) && w.length - e.length >= 3) { w = w.slice(0, -e.length); break; }
    }
    for (const s of DERIV) {
      if (w.endsWith(s) && w.length - s.length >= 4) { w = w.slice(0, -s.length); break; }
    }
    if (w.endsWith('ь') && w.length > 3) w = w.slice(0, -1);
    if (w.endsWith('нн')) w = w.slice(0, -1);
    return w;
  }

  function tokens(text) {
    return normalize(text).split(' ').filter(t => t.length >= 3 && !STOP.has(t));
  }

  // Масив унікальних основ для поля search_terms
  function terms(...texts) {
    const set = new Set();
    texts.flat().forEach(t => tokens(t).forEach(x => set.add(stem(x))));
    return [...set];
  }

  // Рядок для $text: { $search } з основ слів запиту
  function query(text) { return terms(text).join(' '); }

  return { normalize, stem, tokens, terms, query, STOP };
})();
