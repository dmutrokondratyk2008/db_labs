-- Схема з методички (users, categories, posts, tags, post_tags, comments)
-- доповнена полями рівнів 2-3: parent_id і статус коментаря, реакції,
-- перегляди за днями, координати, версії постів, сповіщення.
-- Запуск: psql -U postgres -d blog_system -f 01_schema.sql
